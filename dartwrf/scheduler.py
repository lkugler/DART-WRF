import os
import subprocess
import datetime


def generate_and_submit_job(jobname, config, script_to_run='your_main_script.py', modules_to_load=None):
    """
    Generates a job script, writes it to DIR_JOB_SCRIPTS, and submits it.
    The job script directs scheduler output (logs) to DIR_JOB_LOGS.

    Args:
        config (dict): Configuration containing 'scheduler' and 'kwargs' (HPC options).
        script_to_run (str): The primary executable command to be run in the job.
        modules_to_load (list, optional): List of modules (e.g., ['python/3.10', 'cuda/11.8']).
    """
    scheduler = config.scheduler.lower()
    kwargs = config.scheduler_kwargs 
    
    current_dir = os.getcwd()
    DIR_JOB_SCRIPTS = config.dir_archive + '/job_scripts/'
    DIR_JOB_LOGS = config.dir_archive + '/job_logs/'
    
    # --- 1. Determine Scheduler Prefix and Submission Command ---
    if scheduler == 'slurm':
        directive_prefix = '#SBATCH '
        submit_command = 'sbatch'
        log_directive_key = 'output'
        log_format = os.path.join(DIR_JOB_LOGS, 'slurm_job_%j.out')
        
    elif scheduler == 'pbs':
        directive_prefix = '#PBS ' 
        submit_command = 'qsub'
        log_directive_key = 'o'
        log_format = os.path.join(DIR_JOB_LOGS, 'pbs_job_$PBS_JOBID.out')
        
    else:
        raise ValueError(f"Unsupported scheduler: {scheduler}. Must be 'slurm' or 'pbs'.")

    # --- 2. Filename and Path Setup ---
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    script_filename = f"{scheduler.upper()}_{job_name}_{timestamp}.sh"
    full_script_path = os.path.join(current_dir, DIR_JOB_SCRIPTS, script_filename)

    # --- 3. Generate Script Content (Directives) ---
    
    script_content = f"#!/bin/bash\n\n"
    script_content += f"# --- Generated by Python Script ---\n"
    
    # Set the log file path, overriding any user-provided output/error keys
    kwargs[log_directive_key] = log_format
    if scheduler == 'slurm':
        # SLURM requires an explicit error file directive for full control
        kwargs['error'] = os.path.join(DIR_JOB_LOGS, 'slurm_job_%j.err')
        
    for key, value in kwargs.items():
        if scheduler == 'slurm':
            directive_line = f"{directive_prefix} --{key}={value}"
        
        elif scheduler == 'pbs':
            if key in ['nodes', 'walltime', 'mem', 'ncpus', 'select']:
                directive_line = f"{directive_prefix}-l {key}={value}"
            elif len(key) == 1 and key not in ['l', 'o', 'e']:
                directive_line = f"{directive_prefix}-{key} {value}"
            else:
                # Catch-all for full-name PBS flags or log directives already handled
                directive_line = f"{directive_prefix}{key} {value}"

        script_content += f"{directive_line}\n"

    # --- 4. Environment Setup and Execution ---
    
    # Change directory to the job submission location for relative paths to work
    script_content += f"\n# --- Directory and Environment Setup ---\n"
    script_content += f"cd {current_dir}\n"
    
    if modules_to_load:
        for module in modules_to_load:
            script_content += f"module load {module}\n"

    script_content += f"\n# --- Execution ---\n"
    script_content += f"echo \"Starting job...\"\n"
    script_content += f"python {script_to_run}\n"
    script_content += f"echo \"Job finished.\"\n"
    
    # --- 5. Write to File and Submit ---
    
    try:
        # Write the script content to the file in dir_job_scripts
        with open(full_script_path, 'w') as f:
            f.write(script_content)
        
        # Make the script executable
        os.chmod(full_script_path, 0o755) 

        print(f"Generated script saved to: **{full_script_path}**")
        
        # Execute the sbatch or qsub command
        result = subprocess.run(
            [submit_command, full_script_path],
            capture_output=True,
            text=True,
            check=True
        )
        
        job_id = result.stdout.strip().split()[-1]
        print(f"Job submitted successfully! ID: {job_id}")
        print(f"Logs will be in the **{DIR_JOB_LOGS}/** directory.")
        return job_id
        
    except subprocess.CalledProcessError as e:
        print(f"Error submitting job (Return Code {e.returncode}):")
        print(f"STDERR: {e.stderr.strip()}")
        return None
    except Exception as e:
        print(f"An unexpected error occurred: {e}")
        return None